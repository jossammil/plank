# Builds examples/sample.pqv.html: a small saved viewer (10,000 synthetic rows,
# 30 columns of every type) kept in the repository for trying pqview without
# R. Run from the package root: Rscript examples/make-sample.R
if (requireNamespace("pkgload", quietly = TRUE) && file.exists("DESCRIPTION")) {
  pkgload::load_all(quiet = TRUE)
} else {
  library(pqview)
}

source("examples/demo-data.R")
sample_data <- demo_data(10000)

out <- save_pqview(sample_data, "examples/sample.pqv.html", title = "pqview sample",
  notes = "10,000 synthetic records with 30 columns of every type. Generated by examples/make-sample.R.",
  sort = "-income",
  pin = "record_id",
  formats = list(income = list(decimals = 0, big_mark = TRUE)),
  views = list(
    "Older West" = pqview_view(
      columns = c("record_id", "state", "region", "age", "income", "enrolled"),
      where = "age >= 65 AND region = 'West'",
      sort = "-income",
      pin = "record_id"
    ),
    "Region by enrolment" = pqview_view(counts = c("region", "enrolled"))
  ))
cat(sprintf("%s: %d x %d, %.2f MB\n", out, nrow(sample_data), ncol(sample_data), file.size(out) / 1e6))
