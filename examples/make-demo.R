# Builds examples/demo.html: a 100,000 x 30 synthetic data set covering every
# column type. Run from the package root: Rscript examples/make-demo.R
if (requireNamespace("pkgload", quietly = TRUE) && file.exists("DESCRIPTION")) {
  pkgload::load_all(quiet = TRUE)
} else {
  library(pqview)
}

set.seed(42)
n <- 100000
blank <- function(x, p = 0.03) {
  x[sample.int(n, round(n * p))] <- NA
  x
}
states <- c(state.name, "District of Columbia")

demo <- data.frame(
  record_id = sprintf("R%06d", seq_len(n)),
  state = factor(sample(states, n, TRUE)),
  region = sample(c("Northeast", "South", "Midwest", "West"), n, TRUE),
  age = blank(sample(18:95, n, TRUE)),
  income = blank(round(rlnorm(n, 10.8, 0.7), 2), 0.08),
  score = round(rnorm(n, 50, 12), 4),
  enrolled = blank(sample(c(TRUE, FALSE), n, TRUE), 0.05),
  visit_date = blank(as.Date("2022-01-01") + sample(0:1095, n, TRUE)),
  updated_at = as.POSIXct("2024-01-01", tz = "America/Chicago") + sample(0:(366 * 86400), n, TRUE),
  comment = blank(paste(
    sample(c("follow up", "no issues", "needs review", "called patient", "left voicemail"), n, TRUE),
    sample(1000:9999, n, TRUE)
  ), 0.4),
  stringsAsFactors = FALSE
)
for (i in 1:10) demo[[sprintf("measure_%02d", i)]] <- blank(round(rnorm(n, i * 10, i), 3), 0.01)
for (i in 1:5) demo[[sprintf("count_%02d", i)]] <- rpois(n, i * 3)
for (i in 1:5) demo[[sprintf("category_%02d", i)]] <- sample(LETTERS[1:(i + 2)], n, TRUE)
attr(demo$income, "label") <- "Household income (USD)"

t0 <- Sys.time()
save_pqview(demo, "examples/demo.html", title = "Synthetic demo",
  notes = "100,000 synthetic records with 30 columns of every type. Generated by examples/make-demo.R.")
cat(sprintf(
  "demo.html: %d x %d, %.1f MB, written in %.1fs\n",
  nrow(demo), ncol(demo), file.size("examples/demo.html") / 1e6,
  as.numeric(difftime(Sys.time(), t0, units = "secs"))
))

# Row counts the viewer should reproduce for the same filters.
expected <- list(
  total = n,
  age_30_40 = sum(demo$age >= 30 & demo$age <= 40, na.rm = TRUE),
  income_na = sum(is.na(demo$income)),
  region_west_south = sum(demo$region %in% c("West", "South")),
  enrolled_true = sum(demo$enrolled %in% TRUE),
  comment_review = sum(grepl("review", demo$comment, fixed = TRUE)),
  visit_2023_06 = sum(format(demo$visit_date, "%Y-%m") == "2023-06", na.rm = TRUE),
  updated_march_local = sum(format(demo$updated_at, "%Y-%m-%d") >= "2024-03-10" &
    format(demo$updated_at, "%Y-%m-%d") <= "2024-03-10"),
  combo = sum(demo$age >= 30 & demo$age <= 40 & demo$region %in% c("West", "South") &
    demo$enrolled %in% TRUE, na.rm = TRUE),
  search_alaska = sum(demo$state == "Alaska"),
  age_min = min(demo$age, na.rm = TRUE),
  first_sorted_income = sprintf("%s", demo$record_id[order(demo$income, seq_len(n))][1]),
  top_income = max(demo$income, na.rm = TRUE),

  # WHERE queries (same text as typed in the browser)
  q_age_region = sum(demo$age > 30 & demo$region %in% c("West", "South"), na.rm = TRUE),
  q_regex = sum(grepl("^(called|left)", demo$comment) & !is.na(demo$comment)),
  q_like = sum(grepl("review", demo$comment, ignore.case = TRUE) & !is.na(demo$comment)),
  q_null = sum(is.na(demo$income) | demo$income < 20000, na.rm = TRUE),
  q_dates = sum(demo$visit_date >= as.Date("2023-01-01") & demo$visit_date <= as.Date("2023-06-30"), na.rm = TRUE),
  q_year_not = sum(format(demo$visit_date, "%Y") == "2024" & demo$enrolled %in% FALSE, na.rm = TRUE),
  q_age_region_enrolled = sum(demo$age > 30 & demo$region %in% c("West", "South") & demo$enrolled %in% TRUE, na.rm = TRUE),
  q_hidden = sum(demo$measure_03 > 30, na.rm = TRUE),
  q_arith = sum(demo$income / 1000 >= 50, na.rm = TRUE),

  # column filter options
  comment_regex = sum(grepl("^needs|voicemail", demo$comment, ignore.case = TRUE) & !is.na(demo$comment)),
  comment_regex_cs = sum(grepl("^Needs|voicemail", demo$comment) & !is.na(demo$comment)),
  region_exact_west = sum(demo$region == "West"),
  search_regex_ala = sum(grepl("^ala", demo$state, ignore.case = TRUE)),

  # OR column filters: (age >= 61 OR income >= 100000) AND region West
  or_age_income = sum(demo$age >= 61 | demo$income >= 100000, na.rm = TRUE),
  or_age_income_west = sum((demo$age >= 61 | demo$income >= 100000) & demo$region == "West", na.rm = TRUE),

  # exports of region == 'West' (first 10 columns), read back in R
  west_income_sum = sum(demo$income[demo$region == "West"], na.rm = TRUE),
  west_age_na = sum(is.na(demo$age[demo$region == "West"])),
  west_visit_first = format(demo$visit_date[demo$region == "West"][1]),
  west_updated_first = format(demo$updated_at[demo$region == "West"][1], "%Y-%m-%d %H:%M:%S")
)
writeLines(jsonlite::toJSON(expected, auto_unbox = TRUE, digits = NA, pretty = TRUE), "examples/demo-expected.json")
